public class Variables {
    public static void main(String[] args) {
        
        // create/declare a variable
        int age;

        // assign a value to the variable
        age = 25;

        // modify the value of the variable
        age = 30;

        // print the value of the variable
        System.out.println("Age: " + age);

        // output: Age: 30


        // Note : constants variable names are generally written in uppercase letters with underscores separating words.
         int DAYS_IN_WEEK = 7;
         System.out.println("Days in a week: " + DAYS_IN_WEEK);

         // output: Days in a week: 7


         // Error Case :
         int number;
        //  System.out.println("Number: " + number);ss
        //  output: Error: variable number might not have been initialized
        
    }
}
